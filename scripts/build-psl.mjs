// Turns the Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat) into src/psl-rules.txt:
// one rule per line, ICANN and PRIVATE sections alike, internationalised labels in their ASCII (punycode) form so
// they match the hostnames URL() gives. Run: node scripts/build-psl.mjs path/to/public_suffix_list.dat
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/build-psl.mjs public_suffix_list.dat");
const text = readFileSync(src, "utf8");
const version = /VERSION: (\S+)/.exec(text)?.[1] ?? "unknown";
const rules = [];
for (const raw of text.split("\n")) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const bang = line.startsWith("!") ? "!" : "";
  const body = bang ? line.slice(1) : line;
  const ascii = body
    .split(".")
    .map((l) => (l === "*" ? "*" : domainToASCII(l) || l))
    .join(".")
    .toLowerCase();
  rules.push(bang + ascii);
}
writeFileSync(new URL("../src/psl-rules.txt", import.meta.url), `// Public Suffix List ${version}, https://publicsuffix.org/list/ (MPL-2.0). Generated by scripts/build-psl.mjs.\n${rules.join("\n")}\n`);
console.log(`${rules.length} rules, version ${version}`);
